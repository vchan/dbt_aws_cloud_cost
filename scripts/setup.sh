#!/usr/bin/env bash
# One-shot setup for the demo: check for the dbt Fusion CLI, then write .env.
#
# Usage, from the repo root:
#   scripts/setup.sh
#
# Then fill in .env (see .env.example) and:
#   set -a && source .env && set +a        # or: direnv allow
#   dbt deps && dbt seed && dbt build
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)

command -v dbt >/dev/null 2>&1 || {
  echo "error: no 'dbt' on PATH, see README > Install dbt" >&2
  exit 1
}

if [ -e "$ROOT/.env" ]; then
  echo "note: $ROOT/.env already exists, leaving it untouched (delete it to regenerate)."
else
  umask 077
  {
    echo "# Generated by scripts/setup.sh. Add the variables from .env.example."
    echo "DBT_PROFILES_DIR=$ROOT"
    echo "DBT_ENGINE_EXPERIMENTAL_MULTI_ADAPTER=true"
  } > "$ROOT/.env"
  echo "wrote $ROOT/.env"
fi

cat <<'EOT'

setup ok. next:
  1. add LAKE_COMPUTE_AUTH_TOKEN to .env (see .env.example)
  2. gcloud auth application-default login   # BigQuery access (method: oauth)
  3. set -a && source .env && set +a         # or: direnv allow
  4. dbt deps && dbt seed && dbt build
EOT
